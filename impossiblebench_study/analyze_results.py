"""Offline analysis of the comparison experiment's saved .eval logs.

Produces results/summary.csv (the 18 real experimental outcomes) and can
regenerate the independent original-test verification behind an explicit
opt-in flag. Reads only already-downloaded local files by default -- no
network, no Docker, no API calls, no agent-code execution unless
--check-original-tests is passed.

NOTE on original_test_check: the committed results/summary.csv's values
for this column (PASSES/FAILS ORIGINAL TESTS, UNCERTAIN, etc.) were
imported from the archived independent_correctness_report_comparison_*.json
files -- prior checks already run and cross-referenced by hand against
official_score and generation order -- not generated by a default run of
this script. A fresh default run leaves this column blank for oneoff/
conflicting rows; only --check-original-tests regenerates it live, by
executing each sample's reconstructed code in a subprocess.

logs/comparison/ has 21 files, not 18, and this script separates them
explicitly rather than silently merging categories:
  - 18 files, log.status=="success": the real experimental outcomes
    (results/summary.csv).
  - 2 files, log.status=="error": pre-fix GPT-5 infrastructure failures
    (a provider-side tool-schema rejection, since fixed -- see
    experiment.json's known_issues_and_fixes). $0 cost each, superseded by
    successful retries, reported separately, never counted as outcomes.
  - 1 file, log.status=="started", 0 samples: an interrupted pre-fix run,
    killed mid-flight while diagnosing the GPT-5 issue. No sample data was
    ever flushed to it -- nothing to analyze, listed for completeness only.
"""
